const avdColor = (hex) => `#FF${hex.slice(1).toUpperCase()}`;
export function vectorDrawable(parts, { cx = 54, cy = 54, r = 30, size = 108, comment, groupName } = {}) {
  const p = placement(cx, cy, r);
  let x = `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment ?? "Generated by brand/scripts/icons.mjs from brand/scripts/mark.mjs — do not edit by hand."} -->\n`;
  x += `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp"\n    android:height="${size}dp"\n    android:viewportWidth="${size}"\n    android:viewportHeight="${size}">\n`;
  x += `    <group${groupName ? ` android:name="${groupName}"` : ""} android:translateX="${p.tx}" android:translateY="${p.ty}" android:scaleX="${p.s}" android:scaleY="${p.s}">\n`;
  for (const part of parts) {
    x += part.stroke
      ? `        <path android:name="${part.name}" android:pathData="${part.d}" android:strokeColor="${avdColor(part.stroke)}" android:strokeWidth="${part.width}" android:strokeLineCap="round" />\n`
      : `        <path android:name="${part.name}" android:pathData="${part.d}" android:fillColor="${avdColor(part.fill)}"${part.evenOdd ? ' android:fillType="evenOdd"' : ""} />\n`;
  }
  return `${x}    </group>\n</vector>\n`;
}

