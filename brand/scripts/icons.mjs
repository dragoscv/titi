function construction() {
  const S = 480;
  const k = S / 48;
  let g = "";
  for (let i = 0; i <= 48; i += 2) g += `<path d="M${i * k},0V${S}M0,${i * k}H${S}" stroke="${i % 12 === 0 ? "#3a404a" : "#22262d"}" stroke-width="${i % 12 === 0 ? 1.2 : 0.6}"/>`;
  const ref = `<g fill="none" stroke="#2DD4BF" stroke-width="0.12" stroke-dasharray="0.6 0.4"><circle cx="22" cy="26" r="11"/><circle cx="22" cy="26" r="16.5"/><circle cx="22.5" cy="25" r="18.9"/><path d="M22,0V48M0,26H48"/></g>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S + 80}"><rect width="${S}" height="${S + 80}" fill="${C.graphite}"/>${g}<g transform="scale(${k})" opacity="0.92">${markElements()}</g><g transform="scale(${k})">${ref}</g><text x="12" y="${S + 30}" fill="#9AA3B2" font-family="Manrope" font-size="14">48-unit grid · body r 11 · arc r 16.5 concentric, stroke 2.6 (master) · eye r 1.9 · beak 6.2×6.8</text><text x="12" y="${S + 56}" fill="#9AA3B2" font-family="Manrope" font-size="14">ink radius 18.9 from optical centre (22.5, 25) · small: eye 2.3 / arc 3.0 · micro: eye 2.9 / arc 3.6</text></svg>`;
}

function tvBannerXml() {
  // 320x180 dp: mark left, lettered wordmark right (paths only; no fonts on TV launcher)
  const w = wordmark();
  const h = w.top + w.bottom;
  const scale = 64 / h;
  const p = placement(78, 90, 42);
  let x = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by brand/scripts/icons.mjs — 320x180 Google TV banner: Chirp mark + lettered wordmark. -->\n`;
  x += `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="320dp"\n    android:height="180dp"\n    android:viewportWidth="320"\n    android:viewportHeight="180">\n`;
  x += `    <path android:fillColor="${avdColor(C.graphite)}" android:pathData="M0,0h320v180h-320z" />\n`;
  x += `    <group android:translateX="${p.tx}" android:translateY="${p.ty}" android:scaleX="${p.s}" android:scaleY="${p.s}">\n`;
  for (const part of markParts()) {
    x += part.stroke
      ? `        <path android:pathData="${part.d}" android:strokeColor="${avdColor(part.stroke)}" android:strokeWidth="${part.width}" android:strokeLineCap="round" />\n`
      : `        <path android:pathData="${part.d}" android:fillColor="${avdColor(part.fill)}" />\n`;
  }
  x += `    </group>\n`;
  const tx = 142;
  const ty = 90 - 32 + w.top * scale;
  for (const [, d, fill] of w.parts) x += `    <path android:fillColor="${avdColor(fill)}" android:pathData="${transformPath(d, scale, tx, ty)}" />\n`;
  return `${x}</vector>\n`;
}

/** Bake scale + translate into path data (VectorDrawable paths have no transform). sy may be negative (no arcs then). */
export function transformPath(d, s, tx, ty, sy = s) {
  return d.replace(/([MLHVQCZAmlhvqcza])([^MLHVQCZAmlhvqcza]*)/g, (_, cmd, args) => {
    const n = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
    const up = cmd.toUpperCase();
    const rel = cmd !== up;
    const xy = (i) => (i % 2 === 0 ? (rel ? n[i] * s : n[i] * s + tx) : rel ? n[i] * sy : n[i] * sy + ty);
    let o;
    if (up === "H") o = n.map((v) => (rel ? v * s : v * s + tx));
    else if (up === "V") o = n.map((v) => (rel ? v * sy : v * sy + ty));
    else if (up === "A") o = n.map((v, i) => [0, 1].includes(i % 7) ? v * s : [2, 3, 4].includes(i % 7) ? v : i % 7 === 5 ? (rel ? v * s : v * s + tx) : rel ? v * s : v * s + ty);
    else o = n.map((_, i) => xy(i));
    return cmd + o.map((v) => +v.toFixed(2)).join(",");
  });
}
