function colorset(hex) {
  const c = (i) => (parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16) / 255).toFixed(3);
  return { colors: [{ color: { "color-space": "srgb", components: { red: c(0), green: c(1), blue: c(2), alpha: "1.000" } }, idiom: "universal" }], info: { author: "xcode", version: 1 } };
}

