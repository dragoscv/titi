const FONT = { fontFiles: ["brand/fonts/Manrope-ExtraBold.ttf", "brand/fonts/Manrope-Bold.ttf", "brand/fonts/Manrope-Medium.ttf", "brand/fonts/GeistMono-Medium.ttf"], loadSystemFonts: false, defaultFontFamily: "Manrope" };
