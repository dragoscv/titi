// Output writer shared by the brand build. `--check` compares instead of writing (CI drift gate).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const CHECK = process.argv.includes("--check") || process.argv.includes("--check-text");
const TEXT_ONLY = process.argv.includes("--check-text");
const drift = [];
let written = 0;

/** Write (or in --check mode verify) a repo-relative file. Text is normalised to LF. */
export function out(rel, content) {
  const p = resolve(ROOT, rel);
  const buf = typeof content === "string" ? Buffer.from(content.replace(/\r\n/g, "\n"), "utf8") : Buffer.from(content);
  if (CHECK) {
    if (TEXT_ONLY && typeof content !== "string") return;
    if (!existsSync(p) || !readFileSync(p).equals(buf)) drift.push(rel);
    return;
  }
  mkdirSync(dirname(p), { recursive: true });
  if (existsSync(p) && readFileSync(p).equals(buf)) return;
  writeFileSync(p, buf);
  written++;
}

export function finish(label) {
  if (CHECK) {
    if (drift.length) {
      console.error(`${label}: ${drift.length} generated file(s) out of date:\n  ${drift.join("\n  ")}\nRun: node brand/scripts/build.mjs`);
      process.exit(1);
    }
    console.log(`${label}: no drift`);
  } else console.log(`${label}: ${written} file(s) written`);
}

export const GENERATED = (src) => `Generated by brand/scripts/${src} from brand/tokens — do not edit by hand.`;
